<section class="process-section">
  <div class="section-header">
    <span class="eyebrow">Manufacturing Discipline</span>
    <h2>6-Stage Precision Alloying &amp; Casting Process</h2>
    <p class="section-desc">
      Every metric ton of Zinc Alloy produced at Bhatti Chemicals undergoes rigorous thermodynamic control and elemental verification.
    </p>
  </div>
  <div class="process-grid">
    <div class="process-box">
      <div class="step-badge">01</div>
      <h3>Electrolytic SHG Feedstock</h3>
      <p>Only verified 99.99% Special High Grade zinc is charged into the induction furnace to eliminate pernicious contaminants like tin, lead, and cadmium.</p>
    </div>
    <div class="process-box">
      <div class="step-badge">02</div>
      <h3>Stoichiometric Alloying</h3>
      <p>High-purity master alloys of aluminium (Al 99.9%), electrolytic copper, and magnesium are weighed to ±0.01 kg accuracy to meet exact target formulations.</p>
    </div>
    <div class="process-box">
      <div class="step-badge">03</div>
      <h3>Induction Melting &amp; Degassing</h3>
      <p>Clean medium-frequency induction heating maintains uniform melt temperature (440–460°C) with inert gas rotary degassing to purge dissolved hydrogen and dross.</p>
    </div>
    <div class="process-box">
      <div class="step-badge">04</div>
      <h3>Real-Time Spectrometry (OES)</h3>
      <p>Sample pins are spark-analyzed via Optical Emission Spectrometry prior to tapping, certifying all 12 elemental channels meet ASTM B240 chemistry windows.</p>
    </div>
    <div class="process-box">
      <div class="step-badge">05</div>
      <h3>Continuous Ingot Casting</h3>
      <p>Molten alloy is cast into precision steel molds with controlled water-cooling stages to produce fine-grained, segregation-free ingot microstructures.</p>
    </div>
    <div class="process-box">
      <div class="step-badge">06</div>
      <h3>Heat Stamping &amp; Bundling</h3>
      <p>Solidified ingots are stamped with the alloy grade and melt batch number, stacked into ~1 MT pallets, and secured with four high-tensile steel straps.</p>
    </div>
  </div>
</section>

